function curriculum(modules: { title: string; items: string[] }[]): Program["curriculum"] {
  const types = ["lesson", "lesson", "assignment", "project", "quiz"] as const;
  return modules.map((m, i) => ({
    module: `Module ${i + 1}`,
    title: m.title,
    items: m.items.map((title, j) => ({ type: types[j % types.length]!, title })),
  }));
}

