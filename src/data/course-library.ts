type Spec = {
  slug: string;
  title: string;
  group: CourseGroup;
  cat: string;
  level: Level;
  hours: number;
  tagline: string;
  skills: string[];
  modules: string[];
  instructor: number;
  related?: string[];
};

function s(
  slug: string,
  title: string,
  group: CourseGroup,
  cat: string,
  level: Level,
  hours: number,
  tagline: string,
  skills: string[],
  modules: string[],
  instructor: number,
  related?: string[],
): Spec {
  return {
    slug,
    title,
    group,
    cat,
    level,
    hours,
    tagline,
    skills,
    modules,
    instructor,
    ...(related ? { related } : {}),
  };
}

